<?php

namespace App\Console\Commands;

use App\Enums\AccountType;
use App\Enums\ActivityCategory;
use App\Enums\BusinessCategory;
use App\Enums\ContactType;
use App\Enums\ItemKind;
use App\Enums\MoneyAccountKind;
use App\Enums\OrderFulfillment;
use App\Enums\OrderStatus;
use App\Enums\PaymentMethod;
use App\Enums\PaymentStatus;
use App\Enums\Period;
use App\Enums\StockReason;
use App\Enums\TransactionKind;
use App\Enums\TransactionSource;
use App\Enums\TransactionStatus;
use App\Enums\TransactionType;
use BackedEnum;
use Illuminate\Console\Attributes\Description;
use Illuminate\Console\Attributes\Signature;
use Illuminate\Console\Command;

/**
 * Writes the domain vocabulary from app/Enums to TypeScript, so the frontend
 * never keeps its own copy. VocabularyTest fails when the file is stale.
 */
#[Signature('lais:enums')]
#[Description('Tulis resources/js/types/enums.ts dari app/Enums')]
class GenerateEnumTypes extends Command
{
    public const PATH = 'js/types/enums.ts';

    /**
     * @var list<class-string<BackedEnum>>
     */
    private const ENUMS = [
        ItemKind::class,
        TransactionType::class,
        TransactionKind::class,
        PaymentMethod::class,
        TransactionSource::class,
        TransactionStatus::class,
        ContactType::class,
        StockReason::class,
        Period::class,
        ActivityCategory::class,
        MoneyAccountKind::class,
        BusinessCategory::class,
        OrderStatus::class,
        OrderFulfillment::class,
        PaymentStatus::class,
        AccountType::class,
    ];

    public function handle(): int
    {
        file_put_contents(resource_path(self::PATH), self::render());
        $this->info('resources/'.self::PATH.' ditulis.');

        return self::SUCCESS;
    }

    public static function render(): string
    {
        $blocks = array_map(self::enum(...), self::ENUMS);

        $blocks[] = self::list('soldItemKinds', 'ItemKind', ItemKind::sold());
        $blocks[] = self::list('stockedItemKinds', 'ItemKind', ItemKind::stocked());
        $blocks[] = self::relation('transactionTypeMethods', 'PaymentMethod', fn (TransactionType $type) => $type->methods());
        $blocks[] = self::relation('transactionTypeKinds', 'TransactionKind', fn (TransactionType $type) => $type->kinds());

        return "// Generated by `php artisan lais:enums` from app/Enums. Do not edit.\n\n".implode("\n\n", $blocks)."\n";
    }

    /**
     * @param  class-string<BackedEnum>  $class
     */
    private static function enum(string $class): string
    {
        $name = class_basename($class);
        $cases = $class::cases();

        $lines = ["export const {$name} = {"];
        foreach ($cases as $case) {
            $lines[] = "    {$case->name}: ".self::quote((string) $case->value).',';
        }
        $lines[] = '} as const;';
        $lines[] = '';
        $lines[] = "export type {$name} = (typeof {$name})[keyof typeof {$name}];";

        if (method_exists($class, 'label')) {
            $lines[] = '';
            $lines[] = 'export const '.lcfirst($name)."Labels: Record<{$name}, string> = {";
            foreach ($cases as $case) {
                $lines[] = '    '.$case->value.': '.self::quote($case->label()).',';
            }
            $lines[] = '};';
        }

        return implode("\n", $lines);
    }

    /**
     * @param  list<BackedEnum>  $cases
     */
    private static function list(string $name, string $type, array $cases): string
    {
        return "export const {$name}: readonly {$type}[] = [".implode(', ', array_map(fn (BackedEnum $case) => self::quote((string) $case->value), $cases)).'];';
    }

    /**
     * @param  callable(TransactionType): list<BackedEnum>  $of
     */
    private static function relation(string $name, string $type, callable $of): string
    {
        $lines = ["export const {$name}: Record<TransactionType, readonly {$type}[]> = {"];
        foreach (TransactionType::cases() as $transactionType) {
            $values = array_map(fn (BackedEnum $case) => self::quote((string) $case->value), $of($transactionType));
            $lines[] = "    {$transactionType->value}: [".implode(', ', $values).'],';
        }
        $lines[] = '};';

        return implode("\n", $lines);
    }

    private static function quote(string $text): string
    {
        return "'".addcslashes($text, "'\\")."'";
    }
}
